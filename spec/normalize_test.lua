describe("normalize (no 5h limit)", function()
	it("reads an Ultra answer without a session window", function()
		local st = normalize.from_api(H.json("spec/fixtures/api_ultra.json"), 1794400000)
		assert_nil(st.five_hour)
		assert_eq(st.no_session_limit, true)
		assert_eq(st.seven_day.percent, 50)
		assert_eq(#st.scoped, 1)
		assert_eq(st.scoped[1].name, "Fable")
		assert_true(normalize.has_data(st))
	end)
	it("keeps the flag off while the answer has a session window, unknown without data", function()
		assert_eq(normalize.from_api(H.json("spec/fixtures/api_limits.json"), 1).no_session_limit, false)
		assert_eq(normalize.from_api(H.json("spec/fixtures/api_legacy.json"), 1).no_session_limit, false)
		assert_eq(normalize.from_api({ five_hour = { utilization = "abc" }, seven_day = { utilization = 4 } }, 1)
			.no_session_limit, false, "an unreadable 5h window still is one")
		assert_nil(normalize.from_api({}, 1).no_session_limit)
	end)
	it("reads a Desktop sample without fh", function()
		local st = normalize.from_desktop({ t = 1794400000000, u = { sd = 50 } }, 1)
		assert_nil(st.five_hour)
		assert_eq(st.no_session_limit, true)
		assert_eq(normalize.from_desktop({ t = 1, u = { fh = 12, sd = 40 } }, 1).no_session_limit, false)
		assert_nil(normalize.from_desktop({ t = 1, u = {} }, 1).no_session_limit)
	end)
	it("settles the flag: a real window wins, the plan decides when unknown", function()
		local real = normalize.settle_session_limit({ five_hour = { percent = 3 }, no_session_limit = true }, true)
		assert_eq(real.no_session_limit, false)
		assert_eq(real.five_hour.percent, 3)
		local function cache()
			return normalize.from_statusline({ rate_limits = { seven_day = { used_percentage = 9 } } }, 7)
		end
		local ultra = normalize.settle_session_limit(cache(), true)
		assert_nil(ultra.five_hour)
		assert_eq(ultra.no_session_limit, true)
		local max = normalize.settle_session_limit(cache(), false)
		assert_true(max.five_hour.assumed, "Max keeps the not-started window")
		assert_nil(max.no_session_limit)
		local known = cache()
		known.no_session_limit = false
		assert_true(normalize.settle_session_limit(known, true).five_hour.assumed, "a known 5h limit stays")
	end)
	it("recognises Ultra by plan or by the 20x tier", function()
		assert_true(normalize.is_ultra("ultra"))
		assert_true(normalize.is_ultra("max", "default_claude_max_20x"))
		assert_eq(normalize.is_ultra("max", "default_claude_max_5x"), false)
		assert_eq(normalize.is_ultra("max"), false)
		assert_eq(normalize.is_ultra(nil, "default_claude_max_20x"), false)
	end)
end)
